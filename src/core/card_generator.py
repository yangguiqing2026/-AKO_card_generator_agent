from pathlib import Path

try:
    import yaml
except ImportError as exc:  # pragma: no cover - depends on runtime environment
    yaml = None
    _YAML_IMPORT_ERROR = exc
else:
    _YAML_IMPORT_ERROR = None


DEFAULT_OUTPUT = "AKO_agent_card.yaml"

REQUIRED_STRING_FIELDS = (
    "id",
    "name",
    "version",
    "author",
    "created_date",
    "status",
    "description",
)

LIST_FIELDS = ("capabilities", "dependencies", "tags")
DICT_FIELDS = ("interfaces", "health_probe", "registry")

# (card field, config field) - order is intentional and deterministic.
CARD_FIELD_MAP = (
    ("agent_id", "id"),
    ("name", "name"),
    ("version", "version"),
    ("author", "author"),
    ("created_date", "created_date"),
    ("status", "status"),
    ("description", "description"),
    ("capabilities", "capabilities"),
    ("dependencies", "dependencies"),
    ("interfaces", "interfaces"),
    ("health_probe", "health_probe"),
    ("registry", "registry"),
    ("tags", "tags"),
)


def _require_yaml():
    if yaml is None:
        raise RuntimeError(
            "PyYAML 未安装，请先执行: python -m pip install -r requirements.txt"
        ) from _YAML_IMPORT_ERROR


def load_config(config_path):
    """Load a YAML config file and return the parsed mapping."""
    _require_yaml()
    path = Path(config_path)
    if not path.is_file():
        raise FileNotFoundError("配置文件不存在: {}".format(path))
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle) or {}
    if not isinstance(data, dict):
        raise ValueError("配置文件根节点必须是映射（key: value）")
    return data


def validate_card_config(config):
    """Validate the agent section and return it."""
    if not isinstance(config, dict):
        raise ValueError("配置必须是映射类型")
    agent = config.get("agent")
    if not isinstance(agent, dict):
        raise ValueError("缺少 agent 配置节，或 agent 不是映射类型")

    for field in REQUIRED_STRING_FIELDS:
        value = agent.get(field)
        if not isinstance(value, str) or not value.strip():
            raise ValueError("agent.{} 必须是非空字符串".format(field))

    for field in LIST_FIELDS:
        if field in agent and not isinstance(agent[field], list):
            raise ValueError("agent.{} 必须是列表".format(field))

    for field in DICT_FIELDS:
        if field in agent and not isinstance(agent[field], dict):
            raise ValueError("agent.{} 必须是映射".format(field))

    output = config.get("output")
    if output is not None and not isinstance(output, dict):
        raise ValueError("output 配置节必须是映射")

    return agent


def build_card(agent):
    """Build an ordered Agent Card mapping from a validated agent section."""
    card = {}
    for card_field, config_field in CARD_FIELD_MAP:
        if config_field in agent:
            card[card_field] = agent[config_field]
    return card


def render_card(card):
    """Render the card as deterministic YAML with AKO header comments."""
    _require_yaml()
    header = "\n".join(
        [
            "# ============================================",
            "# Author: AKO_studio",
            "# Agent Card for: {}".format(card.get("agent_id", "unknown")),
            "# Generated by: AKO_card_generator",
            "# ============================================",
            "",
        ]
    )
    body = yaml.safe_dump(card, allow_unicode=True, sort_keys=False)
    return header + body


def resolve_output_path(config, output_override=None):
    """Resolve output path from CLI override, config, or default."""
    output_section = config.get("output") or {}
    raw_path = output_override or output_section.get("path") or DEFAULT_OUTPUT
    path = Path(raw_path)
    if not path.is_absolute():
        path = Path.cwd() / path
    return path


def write_card(card, config=None, output_override=None):
    """Render a built card and atomically write it to disk.

    The output path is resolved from ``output_override``, the ``output``
    section of ``config``, or the default name, in that order.

    Returns the resolved output path.
    """
    config = config or {}
    target = resolve_output_path(config, output_override)
    target.parent.mkdir(parents=True, exist_ok=True)

    text = render_card(card)
    temp_path = target.with_name(target.name + ".tmp")
    with temp_path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    temp_path.replace(target)
    return target


def generate_card(config_path, output_override=None):
    """Load, validate, render and atomically write an Agent Card.

    Returns (output_path, card_mapping).
    """
    config = load_config(config_path)
    agent = validate_card_config(config)
    card = build_card(agent)
    target = write_card(card, config, output_override)
    return target, card
